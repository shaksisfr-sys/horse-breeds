const grid = document.getElementById('grid');
const modal = document.getElementById('modal');
const modalImg = document.getElementById('modal-img');
const modalTitle = document.getElementById('modal-title');
const modalDesc = document.getElementById('modal-desc');
const closeBtn = document.getElementById('close');
const searchInput = document.getElementById('search');

// Рендер карточек
function renderCards(list) {
  grid.innerHTML = '';
  list.forEach(breed => {
    const card = document.createElement('div');
    card.className = 'card';
    card.innerHTML = `
      <img src="${breed.img}" alt="${breed.name}" 
           onerror="this.src='https://placehold.co/400x300/e8dcc4/5a3e1b?text=${encodeURIComponent(breed.name)}'">
      <h3>${breed.name}</h3>
    `;
    card.addEventListener('click', () => openModal(breed));
    grid.appendChild(card);
  });
}

// Открытие модалки
function openModal(breed) {
  modalImg.src = breed.img;
  modalImg.onerror = () => {
    modalImg.src = `https://placehold.co/600x400/e8dcc4/5a3e1b?text=${encodeURIComponent(breed.name)}`;
  };
  modalTitle.textContent = breed.name;
  modalDesc.textContent = breed.desc;
  modal.classList.add('active');
  document.body.style.overflow = 'hidden';
}

// Закрытие
function closeModal() {
  modal.classList.remove('active');
  document.body.style.overflow = '';
}

closeBtn.addEventListener('click', closeModal);
modal.addEventListener('click', e => {
  if (e.target === modal) closeModal();
});
document.addEventListener('keydown', e => {
  if (e.key === 'Escape') closeModal();
});

// Поиск
searchInput.addEventListener('input', e => {
  const q = e.target.value.toLowerCase();
  const filtered = breeds.filter(b => b.name.toLowerCase().includes(q));
  renderCards(filtered);
});

// Старт
renderCards(breeds);
